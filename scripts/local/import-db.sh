#!/bin/bash
#
# Recreates the local database from a dump and leaves the site usable:
#
#   1. drop + create the database and load the dump
#   2. sanitize with plain SQL (scripts/local/sanitize.sql) BEFORE Drupal
#      bootstraps once: test e-mail addresses, no queued pushes or mails,
#      no sessions, no production secrets in dr_variable
#   3. first bootstrap: known local password for every account, mail_system
#      checked (scripts/local/post-import.php)
#   4. drush updb + cc all
#   5. when the source was a raw production dump: re-dump the sanitized
#      database to .local/dumps/local-sanitized.sql.gz and delete the raw file
#
# Usage: import-db.sh [dump.sql.gz]
# Without an argument it takes the newest prod-raw-*.sql.gz, or
# local-sanitized.sql.gz when there is no raw dump.

set -euo pipefail

. "$(dirname "$0")/lib.sh"
# Only the database has to be up: web is stopped below and stays stopped if
# the import fails before the data is sanitized.
require_services db

SANITIZED="$DUMPS/local-sanitized.sql.gz"
DUMP="${1:-}"
if [ -z "$DUMP" ]; then
  DUMP="$(ls -t "$DUMPS"/prod-raw-*.sql.gz 2>/dev/null | head -1 || true)"
  [ -z "$DUMP" ] && [ -f "$SANITIZED" ] && DUMP="$SANITIZED"
fi
if [ -z "$DUMP" ] || [ ! -f "$DUMP" ]; then
  echo "No hay ningún volcado en $DUMPS. Ejecuta antes: make pull-db" >&2
  exit 1
fi

if [ ! -f "$DOCROOT/index.php" ] || [ ! -f "$DOCROOT/sites/default/settings.php" ]; then
  echo "Falta el docroot o su settings.php. Ejecuta antes: make pull-code" >&2
  exit 1
fi

# The dump expands to roughly 12x its compressed size inside the db volume.
require_free_mb 6144

# The mailsystem module deletes from 'mail_system' every class it cannot load.
# If the module were not mounted, the first bootstrap would wipe the myapi_*
# keys, so this is checked before Drupal runs at all (and again, from inside
# the container, right before that first bootstrap).
if [ ! -r "$REPO/includes/myapi.mailsystem.inc" ]; then
  echo "No se encuentra includes/myapi.mailsystem.inc en el repositorio. Se cancela antes de importar." >&2
  exit 1
fi

echo "Importando $(basename "$DUMP") ($(du -h "$DUMP" | cut -f1))..."

# No request may bootstrap a half-imported, not yet sanitized database.
dc stop web >/dev/null

db_root <<SQL
DROP DATABASE IF EXISTS \`$DB_NAME\`;
CREATE DATABASE \`$DB_NAME\` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
GRANT ALL PRIVILEGES ON \`$DB_NAME\`.* TO '$DB_USER'@'%';
SQL

START="$(date +%s)"
gzip -dc "$DUMP" | db_root \
  --init-command="SET SESSION foreign_key_checks=0, unique_checks=0" "$DB_NAME"
echo "Carga terminada en $(( $(date +%s) - START )) s."

echo "Saneando datos (SQL, antes del primer arranque de Drupal)..."
db_root "$DB_NAME" < "$LOCAL_SCRIPTS_DIR/sanitize.sql"

"$LOCAL_SCRIPTS_DIR/check-sanitized.sh"

# 'mail_system' exactly as it came in the dump, read with SQL before Drupal
# can touch it. The mailsystem module rewrites the variable on bootstrap when
# it cannot load one of the classes it names, and it does so silently.
MAIL_SYSTEM_B64="$(db_root -N -B "$DB_NAME" -e "SELECT REPLACE(TO_BASE64(value), '\\n', '') FROM dr_variable WHERE name = 'mail_system'")"

# Classes named <Format>__<Mail> are generated by mailsystem into
# files/mailsystem/, which pull-code.sh brings on purpose. Checked here, before
# the first bootstrap, because afterwards the damage is already done.
for class in $(printf '%s' "$MAIL_SYSTEM_B64" | base64 -d | grep -oE '"[A-Za-z0-9]+__[A-Za-z0-9]+"' | tr -d '"' | sort -u); do
  if [ ! -f "$DOCROOT/sites/default/files/mailsystem/$class.mail.inc" ]; then
    echo "Falta sites/default/files/mailsystem/$class.mail.inc: mailsystem borraría esa clase de mail_system." >&2
    echo "Ejecuta 'make pull-code' y vuelve a importar. El contenedor web queda parado." >&2
    exit 1
  fi
done

dc up -d web >/dev/null 2>&1
for _ in $(seq 1 30); do
  web_exec test -S /run/php/php8.3-fpm.sock 2>/dev/null && break
  sleep 1
done
if ! web_exec test -r /var/www/html/sites/all/modules/myapi/includes/myapi.mailsystem.inc; then
  echo "www-data no puede leer el módulo myapi dentro del contenedor. Se cancela antes del primer arranque de Drupal." >&2
  exit 1
fi

post_import() {
  dc exec -T -u www-data \
    -e LOCAL_USER_PASSWORD="${LOCAL_USER_PASSWORD:-Local.1234}" \
    -e EXPECTED_MAIL_SYSTEM_B64="$MAIL_SYSTEM_B64" web \
    drush --uri="$LOCAL_BASE_URL" php-script \
    /var/www/html/sites/all/modules/myapi/scripts/local/post-import.php "$@"
}

echo "Primer arranque: contraseñas locales y comprobación de mail_system..."
post_import

echo "Aplicando updates pendientes y limpiando caché..."
drush_local updb -y
drush_local cc all
post_import verify

case "$(basename "$DUMP")" in
  prod-raw-*)
    echo "Guardando el volcado saneado y borrando el de producción..."
    dc exec -T -e MYSQL_PWD="$DB_ROOT_PASSWORD" db \
      mariadb-dump -uroot --single-transaction --quick "$DB_NAME" | gzip -c > "$SANITIZED.partial"
    gzip -t "$SANITIZED.partial"
    chmod 600 "$SANITIZED.partial"
    mv "$SANITIZED.partial" "$SANITIZED"
    rm -f "$DUMP"
    echo "Queda solo $SANITIZED ($(du -h "$SANITIZED" | cut -f1)); 'make reset' reimporta desde ahí."
    ;;
esac

echo
echo "Sitio listo: $LOCAL_BASE_URL  (Mailpit: http://localhost:$MAILPIT_PORT)"
echo "Contraseña de todas las cuentas: la de LOCAL_USER_PASSWORD en .env"
