#!/bin/bash
#
# Writes .local/docroot/sites/default/settings.php for the local containers:
# database of the db container, local base URL, all mail through Mailpit and
# every external integration switched off. Values come from .env; the file is
# gitignored and holds no production credential.
#
# Machine-specific additions (e.g. Firebase credentials of a test project) go
# in .local/settings.overrides.php, which this file includes last and this
# script never overwrites.

set -euo pipefail

. "$(dirname "$0")/lib.sh"

SETTINGS="$DOCROOT/sites/default/settings.php"
SALT_FILE="$LOCAL_DIR/hash_salt"
mkdir -p "$DOCROOT/sites/default"

# Kept across regenerations: changing the salt invalidates sessions and
# one-time login links.
if [ ! -s "$SALT_FILE" ]; then
  openssl rand -hex 32 > "$SALT_FILE"
  chmod 600 "$SALT_FILE"
fi

php_quote() { printf "%s" "$1" | sed "s/\\\\/\\\\\\\\/g; s/'/\\\\'/g"; }

[ -f "$SETTINGS" ] && chmod u+w "$SETTINGS"
cat > "$SETTINGS" <<PHP
<?php

/**
 * @file
 * LOCAL development settings. Generated by scripts/local/gen-settings.sh from
 * .env — edit .env (or .local/settings.overrides.php) and regenerate instead
 * of editing this file.
 */

\$databases['default']['default'] = array(
  'driver' => 'mysql',
  'database' => '$(php_quote "$DB_NAME")',
  'username' => '$(php_quote "$DB_USER")',
  'password' => '$(php_quote "$DB_PASSWORD")',
  'host' => 'db',
  'port' => '3306',
  'prefix' => 'dr_',
);

\$update_free_access = FALSE;
\$drupal_hash_salt = '$(cat "$SALT_FILE")';

// Web requests keep the host they arrived with, so the same site answers on
// localhost, 10.0.2.2 (Android emulator) and the LAN address of this machine,
// and the URLs it returns (files, links) work from each of them. Drush has no
// request to read the host from, so it gets the configured one.
if (PHP_SAPI === 'cli') {
  \$base_url = '$(php_quote "$LOCAL_BASE_URL")';
}

// Same PHP session values as production's settings.php.
ini_set('session.gc_probability', 1);
ini_set('session.gc_divisor', 100);
ini_set('session.gc_maxlifetime', 200000);
ini_set('session.cookie_lifetime', 2000000);

\$conf['404_fast_paths_exclude'] = '/\/(?:styles)|(?:system\/files)\//';
\$conf['404_fast_paths'] = '/\.(?:txt|png|gif|jpe?g|css|js|ico|swf|flv|cgi|bat|pl|dll|exe|asp)\$/i';
\$conf['404_fast_html'] = '<!DOCTYPE html><html><head><title>404 Not Found</title></head><body><h1>Not Found</h1><p>The requested URL "@path" was not found on this server.</p></body></html>';

\$conf['file_private_path'] = '/var/www/private';
\$conf['file_temporary_path'] = '/tmp';

// localhost, the Android emulator alias and private LAN ranges only.
\$conf['trusted_host_patterns'] = array(
  '^localhost\$',
  '^127\.0\.0\.1\$',
  '^10\.\d+\.\d+\.\d+\$',
  '^192\.168\.\d+\.\d+\$',
  '^172\.(1[6-9]|2\d|3[01])\.\d+\.\d+\$',
  '^[a-z0-9-]+\.local\$',
);

// Errors go to the PHP log and watchdog, never to the response: a notice
// printed into a JSON body breaks the envelope (same as production).
\$conf['error_level'] = 0;

// Cron only runs when asked for (make cron), never as a side effect of a
// page view.
\$conf['cron_safe_threshold'] = 0;

// ---------------------------------------------------------------------------
// Mail: everything is delivered to the mailpit container.
//
// The 'mail_system' variable is deliberately NOT overridden here: it stays as
// imported from production (default-system = HTMLMailSystem__SmtpMailSystem,
// myapi_* keys = MyapiHtmlMailSystem), so the same classes format and send
// the mail. Only the transport the smtp module uses is replaced. \$conf wins
// over the variable table, so no admin form or update can point it elsewhere.
// ---------------------------------------------------------------------------
\$conf['smtp_on'] = 1;
// smtp 7.x-1.9 only logs the message when this is off.
\$conf['smtp_deliver'] = TRUE;
\$conf['smtp_host'] = 'mailpit';
\$conf['smtp_hostbackup'] = '';
\$conf['smtp_port'] = '1025';
\$conf['smtp_protocol'] = 'standard';
\$conf['smtp_username'] = '';
\$conf['smtp_password'] = '';
\$conf['smtp_queue'] = FALSE;
\$conf['smtp_queue_fail'] = FALSE;
\$conf['smtp_reroute_address'] = '';
\$conf['smtp_debugging'] = 0;

// ---------------------------------------------------------------------------
// External integrations: off.
// ---------------------------------------------------------------------------
// OneSignal push: with empty credentials myapi_onesignal_is_configured() is
// FALSE and nothing is sent to any device.
\$conf['myapi_onesignal_app_id'] = '';
\$conf['myapi_onesignal_rest_api_key'] = '';
// Firebase custom tokens (chat): no service account, so the endpoint answers
// its "not configured" error. Put a TEST project in settings.overrides.php.
\$conf['myapi_firebase_service_account'] = array();
\$conf['myapi_firebase_database_url'] = '';
// Bot endpoints (n8n): a key that only exists on this machine.
\$conf['myapi_bot_api_key'] = '$(php_quote "${LOCAL_BOT_API_KEY:-local-bot-api-key}")';

// Safety net for anything else that calls out with drupal_http_request()
// (update status, feeds, a contrib module): requests to hosts outside the
// exceptions are sent to a proxy that does not exist and fail at once.
\$conf['proxy_server'] = '127.0.0.1';
\$conf['proxy_port'] = 9;
\$conf['proxy_exceptions'] = array('127.0.0.1', 'localhost', 'mailpit', 'db');
\$conf['update_notify_emails'] = array();

if (file_exists('/var/www/html/sites/default/settings.overrides.php')) {
  include '/var/www/html/sites/default/settings.overrides.php';
}
PHP

# Optional per-machine overrides live outside the docroot copy so that
# pull-code.sh (rsync --delete) never removes them.
OVERRIDES="$LOCAL_DIR/settings.overrides.php"
if [ -f "$OVERRIDES" ]; then
  cp "$OVERRIDES" "$DOCROOT/sites/default/settings.overrides.php"
fi

chmod 644 "$SETTINGS"
echo "settings.php local generado: $SETTINGS"
