  public function __call($name, $arguments) {
    throw new RuntimeException('MyapiTestSelectQuery: ' . $name . '() is not supported by the fixture query builder.');
  }

  #[\ReturnTypeWillChange]
  public function getIterator() {
    return new ArrayIterator($this->rows());
  }

  /**
   * Records the query and answers the fixture rows it selects.
   */
  public function execute() {
    $GLOBALS['myapi_test_db_queries'][] = [
      'table'      => $this->table,
      'alias'      => $this->alias,
      'fields'     => $this->fields,
      'select_all' => $this->select_all,
      'conditions' => $this->conditions,
      'where'      => $this->where,
      'joins'      => $this->joins,
      'order'      => $this->order,
      'range'      => $this->range,
      'count'      => $this->count_mode,
      'group_by'   => $this->group_by,
      'expressions' => $this->expressions,
      'tags'       => $this->tags,
      'extenders'  => $this->extenders,
    ];

    if ($this->count_mode) {
      // One row, one column, exactly as COUNT(*) answers — fetchField() reads
      // it positionally, so the column name is arbitrary.
      return new MyapiTestStatement([['expression' => count($this->matchedRows())]]);
    }

    return new MyapiTestStatement($this->rows());
  }

  /**
   * Filter, then order, then range, then project — the order a database
   * applies them in.
   */
  private function rows() {
    // A grouped query collapses before it is ordered or ranged, the way SQL
    // does it: aggregate first, then sort and slice the aggregated rows.
    if ($this->group_by || $this->hasAggregate()) {
      $rows = $this->sort($this->aggregate($this->matchedRows()));

      return $this->range !== NULL
        ? array_slice($rows, $this->range['start'], $this->range['length'])
        : $rows;
    }

    $rows = $this->matchedRows();

    // A NON-aggregate expression is a computed column of each row, and it is
    // computed BEFORE the sort because that is what the ORDER BY names: the
    // marketplace listing orders by '(column IS NULL)' to push the providers
    // with no rating or no rate to the end (SPEC 83). Computing it after
    // sorting would leave the ORDER BY reading a column that does not exist
    // yet, and the nulls would land wherever the fixture happened to sit.
    if ($this->expressions) {
      $rows = array_map([$this, 'computeExpressions'], $rows);
    }

    $rows = $this->sort($rows);

    if ($this->range !== NULL) {
      $rows = array_slice($rows, $this->range['start'], $this->range['length']);
    }

    return array_map([$this, 'project'], $rows);
  }

  /**
   * Collapses the matched rows into one row per GROUP BY value (SPEC 79).
   *
   * The fixture rows are the rows the JOINs would produce — one per
   * (provider, category) pair for the category counter — because joins are
   * recorded and never resolved here. Grouping them is therefore the same
   * arithmetic the database does over the same set.
   *
   * Groups come out in the order their first row appears in the fixture. Real
   * SQL guarantees no order without an ORDER BY, so no test should depend on
   * it; what it must not do is reorder rows behind a test's back, hence the
   * insertion order.
   */
  private function aggregate(array $rows) {
    $groups = [];
    foreach ($rows as $row) {
      $key = [];
      foreach ($this->group_by as $field) {
        $key[] = (string) $this->value($row, $field);
      }
      $groups[implode("\0", $key)][] = $row;
    }

    $aggregated = [];
    foreach ($groups as $group) {
      $projected = [];
      foreach ($this->fields as $field) {
        $projected[$field] = isset($this->expressions[$field])
          ? $this->evaluate($this->expressions[$field], $group)
          : $this->value($group[0], isset($this->field_sources[$field]) ? $this->field_sources[$field] : $field);
      }
      $aggregated[] = $projected;
    }

    return $aggregated;
  }

  /**
   * Whether any expression of this query is an aggregate (SPEC 83).
   *
   * The split that tells the two kinds of addExpression() apart: COUNT(...)
   * collapses rows and is answered by aggregate(), while '(x IS NULL)' is a
   * computed column of each row and is answered by computeExpressions(). Before
   * SPEC 83 every expression was an aggregate, so the presence of one was
   * enough to take the grouped path.
   */
  private function hasAggregate() {
    foreach ($this->expressions as $expression) {
      if (preg_match('/^\s*(COUNT|SUM|AVG|MIN|MAX)\s*\(/i', $expression)) {
        return TRUE;
      }
    }

    return FALSE;
  }

  /**
   * Adds the computed columns of one row, keyed by their alias (SPEC 83).
   */
  private function computeExpressions(array $row) {
    foreach ($this->expressions as $alias => $expression) {
      $row[$alias] = $this->evaluateRow($expression, $row);
    }

    return $row;
  }

  /**
   * Evaluates one non-aggregate expression over a single row (SPEC 83).
   *
   * Two shapes, which are the two this module writes:
   *
   *  - '(alias.column IS NULL)' — answers 1 or 0, the way SQL answers a
   *    boolean, so ORDER BY over it puts the rows WITH a value first.
   *  - a bare integer, which is the '1' of an EXISTS sub-select's select list.
   *
   * The column is resolved through the query's own alias map first: a fixture
   * row carries a joined column under the ALIAS the query gave it
   * ('rating_avg'), not under its qualified name — the rule stated in the class
   * docblock. Anything else throws rather than answering a plausible 0.
   */
  private function evaluateRow($expression, array $row) {
    $normalized = preg_replace('/\s+/', ' ', trim($expression));

    if (preg_match('/^\(?\s*([A-Za-z0-9_.]+)\s+IS NULL\s*\)?$/i', $normalized, $m)) {
      $alias = array_search($m[1], $this->field_sources, TRUE);
      $key = $alias !== FALSE ? $alias : $m[1];

      return $this->value($row, $key) === NULL ? 1 : 0;
    }

    if (preg_match('/^\d+$/', $normalized)) {
      return (int) $normalized;
    }

    throw new RuntimeException('MyapiTestSelectQuery: unsupported row expression "' . $expression . '".');
  }

  /**
   * Evaluates one aggregate expression over the rows of a group (SPEC 79).
   *
   * Understands COUNT(*), COUNT(alias.column) — which skips NULLs, as SQL
   * does — and COUNT(DISTINCT alias.column). Anything else throws: a stub that
   * guessed at SUM() or AVG() would answer a number that looks right and is
   * not, which is worse than not supporting it.
   */
  private function evaluate($expression, array $rows) {
    $normalized = preg_replace('/\s+/', ' ', trim($expression));

    if (preg_match('/^COUNT\(\s*\*\s*\)$/i', $normalized)) {
      return count($rows);
    }

    if (preg_match('/^COUNT\(\s*(DISTINCT\s+)?([A-Za-z0-9_.]+)\s*\)$/i', $normalized, $m)) {
      $values = [];
      foreach ($rows as $row) {
        $value = $this->value($row, $m[2]);
        if ($value !== NULL) {
          $values[] = $value;
        }
      }

      return $m[1] ? count(array_unique($values)) : count($values);
    }

    throw new RuntimeException('MyapiTestSelectQuery: unsupported expression "' . $expression . '".');
  }

  /**
   * Reads a column off a fixture row by its qualified name, its alias or its
   * bare column name (SPEC 79).
   *
   * The three-step fallback exists because a grouped query names the same
   * column three ways at once: the condition writes 'c.field_categories_tid',
   * the projection aliases it to 'tid', and the fixture row — which is the
   * joined row, written flat — carries plain 'field_categories_tid'. Used only
   * by the aggregation path, so the projection of every non-grouped query is
   * untouched.
   */
  private function value(array $row, $field) {
    if (array_key_exists($field, $row)) {
      return $row[$field];
    }

    $bare = $this->column($field);

    return array_key_exists($bare, $row) ? $row[$bare] : NULL;
  }

  /**
   * The fixture rows that survive the conditions and the where() fragments,
   * before any ordering, range or projection.
   */
  private function matchedRows() {
    $rows = isset($GLOBALS['myapi_test_db'][$this->table]) ? $GLOBALS['myapi_test_db'][$this->table] : [];
    $rows = array_map(function ($row) {
      return (array) $row;
    }, $rows);

    return array_values(array_filter($rows, [$this, 'matches']));
  }

  private function matches(array $row) {
    foreach ($this->conditions as $condition) {
      if ($condition['operator'] === 'EXISTS') {
        if (!$condition['value']->existsFor($row)) {
          return FALSE;
        }
        continue;
      }
      if ($condition['operator'] === 'GROUP') {
        if (!$this->matchesGroup($row, $condition['group'])) {
          return FALSE;
        }
        continue;
      }
      $column = $this->conditionKey($row, $condition['field']);
      if (!array_key_exists($column, $row)) {
        continue;
      }
      if (!$this->compare($row[$column], $condition['value'], $condition['operator'])) {
        return FALSE;
      }
    }

    foreach ($this->where as $fragment) {
      $column = $this->conditionKey($row, $fragment['field']);
      if (!array_key_exists($column, $row)) {
        continue;
      }
      // NULL is what a LEFT JOIN answers for a node with no row in the joined
      // field table, and SQL compares it to nothing: a bound always excludes
      // it, which is the documented behaviour of the date filter.
      if ($row[$column] === NULL) {
        return FALSE;
      }
      $actual = substr((string) $row[$column], 0, $fragment['length']);
      if (!$this->compare($actual, $fragment['value'], $fragment['operator'])) {
        return FALSE;
      }
    }

    return TRUE;
  }

  /**
   * Evaluates a db_or() / db_and() group over one fixture row (SPEC 77).
   *
   * Same laxness as the top-level conditions, applied one level down: a
   * sub-condition on a column the fixture does not carry is UNKNOWN and does
   * not participate. A group whose sub-conditions are all unknown is
   * satisfied, exactly as a single skipped condition is — which keeps a test
   * free to seed only the columns its case is about. With at least one known
   * sub-condition, OR needs one of them true and AND needs all of them.
   */
  private function matchesGroup(array $row, MyapiTestConditionGroup $group) {
    $known = 0;
    $true = 0;

    foreach ($group->conditions() as $condition) {
      $column = $this->conditionKey($row, $condition['field']);
      if (!array_key_exists($column, $row)) {
        continue;
      }
      $known++;
      if ($this->compare($row[$column], $condition['value'], $condition['operator'])) {
        $true++;
      }
    }

    if ($known === 0) {
      return TRUE;
    }

    return $group->conjunction() === 'OR' ? $true > 0 : $true === $known;
  }

  /**
   * Loose comparison on purpose: a real result set answers '1' where a fixture
   * writes 1, and no myapi condition depends on telling the two apart.
   */
  private function compare($actual, $expected, $operator) {
    switch ($operator) {
      case '=':
        return $actual == $expected;

      case '!=':
      case '<>':
        return $actual != $expected;

      case '>':
        return $actual > $expected;

      case '>=':
        return $actual >= $expected;

      case '<':
        return $actual < $expected;

      case '<=':
        return $actual <= $expected;

      case 'IN':
        return in_array($actual, (array) $expected);

      case 'NOT IN':
        return !in_array($actual, (array) $expected);

      case 'IS NULL':
        return $actual === NULL;

      case 'IS NOT NULL':
        return $actual !== NULL;
    }

    throw new RuntimeException('MyapiTestSelectQuery: unsupported operator "' . $operator . '".');
  }

  private function sort(array $rows) {
    foreach (array_reverse($this->order) as $order) {
      // Same qualified-then-bare resolution as the conditions (SPEC 77): the
      // ORDER BY of the claims fetch names the very column whose alias
      // collides with node.status, and a fixture that disambiguates it with
      // the qualified key must still sort by it.
      $column = $this->column($order['field']);
      // And, when no row carries the bare column, the ALIAS the query gave it
      // (SPEC 83): the listing orders by 'ra.field_rating_avg_value' while the
      // fixture row carries 'rating_avg', the alias of that very column. Only
      // as a fallback, so every query written before this stays sorted by
      // exactly the key it was sorted by.
      if (!$this->anyRowHas($rows, $column)) {
        $alias = array_search($order['field'], $this->field_sources, TRUE);
        if ($alias !== FALSE) {
          $column = $alias;
        }
      }
      foreach ($rows as $row) {
        if (array_key_exists($order['field'], $row)) {
          $column = $order['field'];
          break;
        }
      }
      $direction = $order['direction'] === 'DESC' ? -1 : 1;
      // usort() is not stable in PHP 7.4, so the original position is carried
      // as the tie-breaker: two rows with the same delta keep the order the
      // fixture wrote them in.
      $indexed = [];
      foreach ($rows as $position => $row) {
        $indexed[] = [$position, $row];
      }
      usort($indexed, function ($a, $b) use ($column, $direction) {
        $left = isset($a[1][$column]) ? $a[1][$column] : NULL;
        $right = isset($b[1][$column]) ? $b[1][$column] : NULL;
        if ($left == $right) {
          return $a[0] <=> $b[0];
        }

        return ($left < $right ? -1 : 1) * $direction;
      });
      $rows = array_column($indexed, 1);
    }

    return $rows;
  }

  private function project(array $row) {
    if ($this->select_all) {
      return $row;
    }

    $projected = [];
    foreach ($this->fields as $field) {
      // The QUALIFIED source first ('fs.field_status_value'), then the alias.
      // A fixture only needs the qualified form when an alias collides with a
      // real column of the base table — 'status' is projected off
      // field_data_field_status while n.status is the published flag, and a
      // flat row cannot hold both (SPEC 77).
      $source = isset($this->field_sources[$field]) ? $this->field_sources[$field] : NULL;

      if ($source !== NULL && array_key_exists($source, $row)) {
        $projected[$field] = $row[$source];
      }
      else {
        $projected[$field] = array_key_exists($field, $row) ? $row[$field] : NULL;
      }
    }

    return $projected;
  }

  /**
   * The fixture key a condition reads: the qualified name when the row carries
   * it, the bare column otherwise (SPEC 77 — same disambiguation as project()).
   */
  /**
   * Whether at least one of the rows carries this exact key (SPEC 83).
   */
  private function anyRowHas(array $rows, $key) {
    foreach ($rows as $row) {
      if (array_key_exists($key, $row)) {
        return TRUE;
      }
    }

    return FALSE;
  }

  private function conditionKey(array $row, $field) {
    return array_key_exists($field, $row) ? $field : $this->column($field);
  }

  private function column($field) {
    $position = strpos($field, '.');

    return $position === FALSE ? $field : substr($field, $position + 1);
  }

}

/**
 * The result of a fixture SELECT (SPEC 74).
 *
 * Answers the four fetchers myapi's read paths use, plus iteration, which is
 * how most of them consume a result. Rows come out as stdClass, exactly as
 * Drupal's default fetch mode delivers them.
 */
class MyapiTestStatement implements IteratorAggregate, Countable {

  private $rows;

  public function __construct(array $rows) {
    $this->rows = $rows;
  }

  #[\ReturnTypeWillChange]
  public function getIterator() {
    return new ArrayIterator($this->fetchAll());
  }

  public function fetchAll() {
    return array_map(function ($row) {
      return (object) $row;
    }, $this->rows);
  }

  public function fetchAllAssoc($key) {
    $result = [];
    foreach ($this->fetchAll() as $row) {
      $result[$row->{$key}] = $row;
    }

    return $result;
  }

  public function fetchCol($index = 0) {
    $column = [];
    foreach ($this->rows as $row) {
      $values = array_values($row);
      $column[] = isset($values[$index]) ? $values[$index] : NULL;
    }

    return $column;
  }

  public function fetchObject() {
    $rows = $this->fetchAll();

    return empty($rows) ? FALSE : $rows[0];
  }

  public function fetchAssoc() {
    return empty($this->rows) ? FALSE : $this->rows[0];
  }

  public function fetchField($index = 0) {
    $column = $this->fetchCol($index);

    return empty($column) ? FALSE : $column[0];
  }

  public function rowCount() {
    return count($this->rows);
  }

  #[\ReturnTypeWillChange]
  public function count() {
    return count($this->rows);
  }

}

/**
 * A db_or() / db_and() condition group (SPEC 77).
 *
 * Drupal's DatabaseCondition, reduced to what myapi builds with it: a
 * conjunction and a flat list of simple conditions. No nesting, because no
 * query in this module nests one — a group inside a group throws rather than
 * being silently flattened into the wrong boolean.
 */
class MyapiTestConditionGroup {

  private $conjunction;
  private $conditions = [];

  public function __construct($conjunction) {
    $this->conjunction = $conjunction;
  }

  public function condition($field, $value = NULL, $operator = NULL) {
    if (!is_string($field)) {
      throw new RuntimeException('MyapiTestConditionGroup: nested groups are not supported.');
    }
    $this->conditions[] = [
      'field'    => $field,
      'value'    => $value,
      'operator' => $operator !== NULL ? strtoupper($operator) : (is_array($value) ? 'IN' : '='),
    ];

    return $this;
  }

  public function isNull($field) {
    $this->conditions[] = ['field' => $field, 'value' => NULL, 'operator' => 'IS NULL'];

    return $this;
