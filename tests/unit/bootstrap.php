  /**
   * Filter, then order, then range, then project — the order a database
   * applies them in.
   */
  private function rows() {
    // A grouped query collapses before it is ordered or ranged, the way SQL
    // does it: aggregate first, then sort and slice the aggregated rows.
    if ($this->group_by || $this->hasAggregate()) {
      $rows = $this->sort($this->aggregate($this->matchedRows()));

      return $this->dedupe($this->range !== NULL
        ? array_slice($rows, $this->range['start'], $this->range['length'])
        : $rows);
    }

    $rows = $this->matchedRows();

    // A NON-aggregate expression is a computed column of each row, and it is
    // computed BEFORE the sort because that is what the ORDER BY names: the
    // marketplace listing orders by '(column IS NULL)' to push the providers
    // with no rating or no rate to the end (SPEC 83). Computing it after
    // sorting would leave the ORDER BY reading a column that does not exist
    // yet, and the nulls would land wherever the fixture happened to sit.
    if ($this->expressions) {
      $rows = array_map([$this, 'computeExpressions'], $rows);
    }

    $rows = $this->sort($rows);

    if ($this->range !== NULL) {
      $rows = array_slice($rows, $this->range['start'], $this->range['length']);
    }

    return $this->dedupe(array_map([$this, 'project'], $rows));
  }

  /**
   * Collapses identical projected rows when distinct() was asked for.
   */
  private function dedupe(array $rows) {
    if (!$this->distinct) {
      return $rows;
    }

    $seen = [];
    $unique = [];
    foreach ($rows as $row) {
      $key = serialize($row);
      if (!isset($seen[$key])) {
        $seen[$key] = TRUE;
        $unique[] = $row;
      }
    }

    return $unique;
  }

  /**
   * Collapses the matched rows into one row per GROUP BY value (SPEC 79).
   *
   * The fixture rows are the rows the JOINs would produce — one per
   * (provider, category) pair for the category counter — because joins are
   * recorded and never resolved here. Grouping them is therefore the same
   * arithmetic the database does over the same set.
   *
   * Groups come out in the order their first row appears in the fixture. Real
   * SQL guarantees no order without an ORDER BY, so no test should depend on
   * it; what it must not do is reorder rows behind a test's back, hence the
   * insertion order.
   */
  private function aggregate(array $rows) {
    $groups = [];
    foreach ($rows as $row) {
      $key = [];
      foreach ($this->group_by as $field) {
        $key[] = (string) $this->value($row, $field);
      }
      $groups[implode("\0", $key)][] = $row;
    }

    // AN UNGROUPED AGGREGATE OVER ZERO ROWS STILL ANSWERS ONE ROW (SPEC 121).
    // 'SELECT SUM(x), COUNT(y) FROM ...' with no GROUP BY and no matching row
    // is one row of (NULL, 0) in SQL, never an empty result — and
    // myapi_condominium_expense_totals() reads exactly that difference: its
    // `$row && $row->total !== NULL` branch is what turns the NULL into the
    // 0.0 the app receives. Answering no rows here would take the `!$row`
    // branch instead and let the empty-condominium case pass for the wrong
    // reason. With a GROUP BY, zero rows means zero groups, which is also what
    // SQL does.
    if (!$groups && !$this->group_by) {
      $groups = [[]];
    }

    $aggregated = [];
    foreach ($groups as $group) {
      $projected = [];
      foreach ($this->fields as $field) {
        if (isset($this->expressions[$field])) {
          $projected[$field] = $this->evaluate($this->expressions[$field], $group);
          continue;
        }
        // A plain column next to an aggregate is only meaningful when the
        // group has rows; over the empty group SQL answers NULL.
        $projected[$field] = $group
          ? $this->value($group[0], isset($this->field_sources[$field]) ? $this->field_sources[$field] : $field)
          : NULL;
      }
      $aggregated[] = $projected;
    }

    return $aggregated;
  }

  /**
   * Whether any expression of this query is an aggregate (SPEC 83).
   *
   * The split that tells the two kinds of addExpression() apart: COUNT(...)
   * collapses rows and is answered by aggregate(), while '(x IS NULL)' is a
   * computed column of each row and is answered by computeExpressions(). Before
   * SPEC 83 every expression was an aggregate, so the presence of one was
   * enough to take the grouped path.
   */
  private function hasAggregate() {
    foreach ($this->expressions as $expression) {
      if (preg_match('/^\s*(COUNT|SUM|AVG|MIN|MAX)\s*\(/i', $expression)) {
        return TRUE;
      }
    }

    return FALSE;
  }

  /**
   * Adds the computed columns of one row, keyed by their alias (SPEC 83).
   */
  private function computeExpressions(array $row) {
    foreach ($this->expressions as $alias => $expression) {
      $row[$alias] = $this->evaluateRow($expression, $row);
    }

    return $row;
  }

  /**
   * Evaluates one non-aggregate expression over a single row (SPEC 83).
   *
   * Two shapes, which are the two this module writes:
   *
   *  - '(alias.column IS NULL)' — answers 1 or 0, the way SQL answers a
   *    boolean, so ORDER BY over it puts the rows WITH a value first.
   *  - a bare integer, which is the '1' of an EXISTS sub-select's select list.
   *
   * The column is resolved through the query's own alias map first: a fixture
   * row carries a joined column under the ALIAS the query gave it
   * ('rating_avg'), not under its qualified name — the rule stated in the class
   * docblock. Anything else throws rather than answering a plausible 0.
   */
  private function evaluateRow($expression, array $row) {
    $normalized = preg_replace('/\s+/', ' ', trim($expression));

    if (preg_match('/^\(?\s*([A-Za-z0-9_.]+)\s+IS NULL\s*\)?$/i', $normalized, $m)) {
      $alias = array_search($m[1], $this->field_sources, TRUE);
      $key = $alias !== FALSE ? $alias : $m[1];

      return $this->value($row, $key) === NULL ? 1 : 0;
    }

    if (preg_match('/^\d+$/', $normalized)) {
      return (int) $normalized;
    }

    // 'SUBSTR(alias.column, 1, 10)' as a COMPUTED COLUMN (SPEC 121), which is
    // how myapi_reservation_busy_rows() projects and orders by the clock day of
    // a stored datetime. Same cut as the where() fragment of the same shape,
    // and NULL stays NULL — a reservation with no date sorts where SQL puts a
    // NULL rather than at the epoch.
    if (preg_match('/^SUBSTR\(\s*([A-Za-z0-9_.]+)\s*,\s*1\s*,\s*(\d+)\s*\)$/i', $normalized, $m)) {
      $alias = array_search($m[1], $this->field_sources, TRUE);
      $key = $alias !== FALSE ? $alias : $m[1];
      $value = $this->value($row, $key);

      return $value === NULL ? NULL : substr((string) $value, 0, (int) $m[2]);
    }

    throw new RuntimeException('MyapiTestSelectQuery: unsupported row expression "' . $expression . '".');
  }

  /**
   * Evaluates one aggregate expression over the rows of a group (SPEC 79).
   *
   * Understands COUNT(*), COUNT(alias.column) — which skips NULLs, as SQL
   * does — and COUNT(DISTINCT alias.column), plus SUM() and AVG() since SPEC
   * 121. Anything else throws: a stub that guessed at an aggregate would
   * answer a number that looks right and is not, which is worse than not
   * supporting it.
   *
   * SUM() AND AVG() ANSWER NULL OVER AN EMPTY SET, and that is the whole
   * reason they are written here rather than as a convenient 0. SQL's SUM of
   * no rows — and of rows that are all NULL — is NULL, not zero, and
   * myapi_condominium_expense_totals() has an explicit `$row->total !== NULL`
   * branch that turns that NULL into the 0.0 the app receives. A stub summing
   * to 0 would make that branch unreachable and the test of an empty
   * condominium pass for the wrong reason.
   *
   * The arithmetic runs over floats because every column these two aggregate
   * is a DECIMAL, which the driver answers as a string.
   */
  private function evaluate($expression, array $rows) {
    $normalized = preg_replace('/\s+/', ' ', trim($expression));

    if (preg_match('/^COUNT\(\s*\*\s*\)$/i', $normalized)) {
      return count($rows);
    }

    if (preg_match('/^(SUM|AVG)\(\s*([A-Za-z0-9_.]+)\s*\)$/i', $normalized, $m)) {
      $values = [];
      foreach ($rows as $row) {
        $value = $this->value($row, $m[2]);
        if ($value !== NULL) {
          $values[] = (float) $value;
        }
      }

      if (!$values) {
        return NULL;
      }

      $sum = array_sum($values);

      return strtoupper($m[1]) === 'SUM' ? $sum : $sum / count($values);
    }

    if (preg_match('/^COUNT\(\s*(DISTINCT\s+)?([A-Za-z0-9_.]+)\s*\)$/i', $normalized, $m)) {
      $values = [];
      foreach ($rows as $row) {
        $value = $this->value($row, $m[2]);
        if ($value !== NULL) {
          $values[] = $value;
        }
      }

      return $m[1] ? count(array_unique($values)) : count($values);
    }

    throw new RuntimeException('MyapiTestSelectQuery: unsupported expression "' . $expression . '".');
  }

  /**
   * Reads a column off a fixture row by its qualified name, its alias or its
   * bare column name (SPEC 79).
   *
   * The three-step fallback exists because a grouped query names the same
   * column three ways at once: the condition writes 'c.field_categories_tid',
   * the projection aliases it to 'tid', and the fixture row — which is the
   * joined row, written flat — carries plain 'field_categories_tid'. Used only
   * by the aggregation path, so the projection of every non-grouped query is
   * untouched.
   */
  private function value(array $row, $field) {
    if (array_key_exists($field, $row)) {
      return $row[$field];
    }

    $bare = $this->column($field);

    return array_key_exists($bare, $row) ? $row[$bare] : NULL;
  }

  /**
   * The fixture rows that survive the conditions and the where() fragments,
   * before any ordering, range or projection.
   */
  private function matchedRows() {
    $rows = isset($GLOBALS['myapi_test_db'][$this->table]) ? $GLOBALS['myapi_test_db'][$this->table] : [];
    $rows = array_map(function ($row) {
      return (array) $row;
    }, $rows);

    return array_values(array_filter($rows, [$this, 'matches']));
  }

  private function matches(array $row) {
    foreach ($this->conditions as $condition) {
      if ($condition['operator'] === 'EXISTS') {
        if (!$condition['value']->existsFor($row)) {
          return FALSE;
        }
        continue;
      }
      if ($condition['operator'] === 'GROUP') {
        if (!$this->matchesGroup($row, $condition['group'])) {
          return FALSE;
        }
        continue;
      }
      $column = $this->conditionKey($row, $condition['field']);
      if (!array_key_exists($column, $row)) {
        continue;
      }
      if (!$this->compare($row[$column], $condition['value'], $condition['operator'])) {
        return FALSE;
      }
    }

    foreach ($this->where as $fragment) {
      if (!$this->matchesFragment($row, $fragment)) {
        return FALSE;
      }
    }

    return TRUE;
  }

  /**
   * Evaluates one parsed where() fragment over a row (SPEC 121).
   *
   * A fragment is either a single comparison or a boolean tree of them — see
   * parseWhere() for the grammar and for why the module writes trees at all.
   * An ATOM whose column the fixture row does not carry is UNKNOWN and does
   * not participate, the same laxness the plain conditions have; inside a tree
   * that means an OR is decided by its known half, which is what lets a test
   * seed only the columns its case is about.
   */
  private function matchesFragment(array $row, array $fragment) {
    $verdict = $this->evaluateFragment($row, $fragment);

    // An entirely unknown fragment does not narrow anything.
    return $verdict === NULL ? TRUE : $verdict;
  }

  /**
   * TRUE, FALSE, or NULL for "this row does not carry the columns involved".
   */
  private function evaluateFragment(array $row, array $fragment) {
    if ($fragment['type'] === 'OR' || $fragment['type'] === 'AND') {
      $known = FALSE;
      $result = $fragment['type'] === 'AND';

      foreach ($fragment['operands'] as $operand) {
        $verdict = $this->evaluateFragment($row, $operand);
        if ($verdict === NULL) {
          continue;
        }
        $known = TRUE;
        $result = $fragment['type'] === 'AND' ? ($result && $verdict) : ($result || $verdict);
      }

      return $known ? $result : NULL;
    }

    $column = $this->conditionKey($row, $fragment['field']);
    if (!array_key_exists($column, $row)) {
      return NULL;
    }
    // NULL is what a LEFT JOIN answers for a node with no row in the joined
    // field table, and SQL compares it to nothing: a bound always excludes it,
    // which is the documented behaviour of the date filter.
    if ($row[$column] === NULL) {
      return FALSE;
    }

    $actual = (string) $row[$column];
    if ($fragment['length'] !== NULL) {
      $actual = substr($actual, 0, $fragment['length']);
    }

    return $this->compare($actual, $fragment['value'], $fragment['operator']);
  }

  /**
   * Evaluates a db_or() / db_and() group over one fixture row (SPEC 77).
   *
   * Same laxness as the top-level conditions, applied one level down: a
   * sub-condition on a column the fixture does not carry is UNKNOWN and does
   * not participate. A group whose sub-conditions are all unknown is
   * satisfied, exactly as a single skipped condition is — which keeps a test
   * free to seed only the columns its case is about. With at least one known
   * sub-condition, OR needs one of them true and AND needs all of them.
   *
   * A SUB-CONDITION MAY ITSELF BE A GROUP SINCE SPEC 98, and that is the one
   * shape this evaluator gained after being written: the provider scope is an
   * OR of "n.nid IN (A ∪ C)" and an AND of the four conditions that define the
   * market, so the nesting is the rule itself and not a style. It recurses
   * with the SAME laxness — a nested group with no known sub-condition
   * anywhere inside it does not participate either, which is what
   * groupKnown() below decides.
   */
  private function matchesGroup(array $row, MyapiTestConditionGroup $group) {
    $known = 0;
    $true = 0;

    foreach ($group->conditions() as $condition) {
      if ($condition['operator'] === 'GROUP') {
        if (!$this->groupKnown($row, $condition['group'])) {
          continue;
        }
        $known++;
        if ($this->matchesGroup($row, $condition['group'])) {
          $true++;
        }
        continue;
      }

      // A correlated EXISTS inside the group (SPEC 121). Always KNOWN: unlike
      // a column condition, it does not depend on the fixture row carrying a
      // particular key — it asks its own table whether a row correlates to
      // this one, and "no row" is a real FALSE and not an unknown. Treating it
      // as unknown would make the 'Personalizado' branch of the bulletin rule
      // vacuously true and show every custom bulletin to everybody.
      if ($condition['operator'] === 'EXISTS') {
        $known++;
        if ($condition['value']->existsFor($row)) {
          $true++;
        }
        continue;
      }

      $column = $this->conditionKey($row, $condition['field']);
      if (!array_key_exists($column, $row)) {
        continue;
      }
      $known++;
      if ($this->compare($row[$column], $condition['value'], $condition['operator'])) {
        $true++;
      }
    }

    if ($known === 0) {
      return TRUE;
    }

    return $group->conjunction() === 'OR' ? $true > 0 : $true === $known;
  }

  /**
   * Tells whether a group carries at least one condition the fixture can
   * answer, at any depth (SPEC 98).
   *
   * The nested counterpart of the array_key_exists() check above: without it,
   * a nested group made entirely of unknown columns would evaluate to TRUE and
   * COUNT as a satisfied branch of the enclosing OR — turning "this row is not
   * about my case" into "this row matches". Unknown must stay unknown however
   * deep it sits.
   */
  private function groupKnown(array $row, MyapiTestConditionGroup $group) {
    foreach ($group->conditions() as $condition) {
      if ($condition['operator'] === 'GROUP') {
        if ($this->groupKnown($row, $condition['group'])) {
          return TRUE;
        }
        continue;
      }

      // An EXISTS is always answerable (SPEC 121) — see matchesGroup().
      if ($condition['operator'] === 'EXISTS') {
        return TRUE;
      }

      if (array_key_exists($this->conditionKey($row, $condition['field']), $row)) {
        return TRUE;
      }
    }

    return FALSE;
  }

  /**
   * Loose comparison on purpose: a real result set answers '1' where a fixture
   * writes 1, and no myapi condition depends on telling the two apart.
   */
  private function compare($actual, $expected, $operator) {
    // SQL'S THREE-VALUED LOGIC, for the one case that changes an answer (SPEC
    // 121). A comparison against NULL is UNKNOWN in SQL, and a WHERE that is
    // UNKNOWN excludes the row — for '<>' just as much as for '='. PHP
    // disagrees: NULL != 'Nuevo' is TRUE, so a stub comparing loosely would
    // hand a payments listing every row whose estado column is NULL, which is
    // precisely what its `<> 'Nuevo'` condition is there to exclude. The
    // where() fragments already had this rule; conditions now share it.
    //
    // 'IS NULL' and 'IS NOT NULL' are the two operators that ASK about the
    // null, so they are answered below and not here.
    if ($actual === NULL && $operator !== 'IS NULL' && $operator !== 'IS NOT NULL') {
      return FALSE;
    }

    switch ($operator) {
      case '=':
        return $actual == $expected;

      case '!=':
      case '<>':
        return $actual != $expected;

      case '>':
        return $actual > $expected;

      case '>=':
        return $actual >= $expected;

      case '<':
        return $actual < $expected;

      case '<=':
        return $actual <= $expected;

      case 'IN':
        return in_array($actual, (array) $expected);

      case 'NOT IN':
        return !in_array($actual, (array) $expected);

      case 'LIKE':
        return $this->like($actual, $expected);

      case 'NOT LIKE':
        return !$this->like($actual, $expected);

      case 'IS NULL':
        return $actual === NULL;

      case 'IS NOT NULL':
        return $actual !== NULL;
    }

    throw new RuntimeException('MyapiTestSelectQuery: unsupported operator "' . $operator . '".');
  }

  /**
   * MySQL's LIKE, as the module's collation resolves it (SPEC 120).
   *
   * The area search filters `n.title` with a LIKE, and what makes that filter
   * accent- and case-insensitive in production is the COLLATION of the column
   * (utf8_general_ci on a standard Drupal 7 install), not anything myapi
   * writes. So the fixture folds both sides with the same map
   * myapi_text_fold() uses: a stub that compared bytes would answer "Jardin
   * does not find Jardín" and quietly contradict the server.
   *
   * `%` and `_` keep their wildcard meaning, and the backslash escaping that
   * db_like() applies is honoured — which is the half worth simulating, since
   * dropping it is exactly how a needle of "100%" would silently start
   * matching every row.
   */
  private function like($subject, $pattern) {
    $subject = myapi_text_fold((string) $subject);
    $pattern = myapi_text_fold((string) $pattern);

    $regex = '';
    $length = strlen($pattern);
    for ($i = 0; $i < $length; $i++) {
      $char = $pattern[$i];
      if ($char === '\\' && $i + 1 < $length) {
        // db_like() escaped this one: it is a literal %, _ or backslash.
        $i++;
        $regex .= preg_quote($pattern[$i], '/');
        continue;
      }
      if ($char === '%') {
        $regex .= '.*';
        continue;
      }
      if ($char === '_') {
        $regex .= '.';
        continue;
      }
      $regex .= preg_quote($char, '/');
    }

    return (bool) preg_match('/^' . $regex . '$/u', $subject);
  }

  private function sort(array $rows) {
    foreach (array_reverse($this->order) as $order) {
      // Same qualified-then-bare resolution as the conditions (SPEC 77): the
      // ORDER BY of the claims fetch names the very column whose alias
      // collides with node.status, and a fixture that disambiguates it with
      // the qualified key must still sort by it.
      $column = $this->column($order['field']);
      // And, when no row carries the bare column, the ALIAS the query gave it
      // (SPEC 83): the listing orders by 'ra.field_rating_avg_value' while the
      // fixture row carries 'rating_avg', the alias of that very column. Only
      // as a fallback, so every query written before this stays sorted by
      // exactly the key it was sorted by.
      if (!$this->anyRowHas($rows, $column)) {
        $alias = array_search($order['field'], $this->field_sources, TRUE);
        if ($alias !== FALSE) {
          $column = $alias;
        }
      }
      foreach ($rows as $row) {
        if (array_key_exists($order['field'], $row)) {
          $column = $order['field'];
          break;
        }
      }
      $direction = $order['direction'] === 'DESC' ? -1 : 1;
      // usort() is not stable in PHP 7.4, so the original position is carried
      // as the tie-breaker: two rows with the same delta keep the order the
      // fixture wrote them in.
      $indexed = [];
      foreach ($rows as $position => $row) {
        $indexed[] = [$position, $row];
      }
      usort($indexed, function ($a, $b) use ($column, $direction) {
        $left = isset($a[1][$column]) ? $a[1][$column] : NULL;
        $right = isset($b[1][$column]) ? $b[1][$column] : NULL;
        if ($left == $right) {
          return $a[0] <=> $b[0];
        }

        return ($left < $right ? -1 : 1) * $direction;
      });
      $rows = array_column($indexed, 1);
    }

    return $rows;
  }

  private function project(array $row) {
    if ($this->select_all) {
      return $row;
    }

    $projected = [];
    foreach ($this->fields as $field) {
      // The QUALIFIED source first ('fs.field_status_value'), then the alias.
      // A fixture only needs the qualified form when an alias collides with a
      // real column of the base table — 'status' is projected off
      // field_data_field_status while n.status is the published flag, and a
      // flat row cannot hold both (SPEC 77).
      $source = isset($this->field_sources[$field]) ? $this->field_sources[$field] : NULL;

      if ($source !== NULL && array_key_exists($source, $row)) {
        $projected[$field] = $row[$source];
      }
      else {
        $projected[$field] = array_key_exists($field, $row) ? $row[$field] : NULL;
      }
    }

    return $projected;
  }

  /**
   * The fixture key a condition reads: the qualified name when the row carries
   * it, the bare column otherwise (SPEC 77 — same disambiguation as project()).
   */
  /**
   * Whether at least one of the rows carries this exact key (SPEC 83).
   */
  private function anyRowHas(array $rows, $key) {
    foreach ($rows as $row) {
      if (array_key_exists($key, $row)) {
        return TRUE;
      }
    }

    return FALSE;
  }

  private function conditionKey(array $row, $field) {
    return array_key_exists($field, $row) ? $field : $this->column($field);
  }

  private function column($field) {
    $position = strpos($field, '.');

    return $position === FALSE ? $field : substr($field, $position + 1);
  }

}

/**
 * The result of a fixture SELECT (SPEC 74).
 *
 * Answers the four fetchers myapi's read paths use, plus iteration, which is
 * how most of them consume a result. Rows come out as stdClass, exactly as
 * Drupal's default fetch mode delivers them.
 */
class MyapiTestStatement implements IteratorAggregate, Countable {

  private $rows;

  public function __construct(array $rows) {
    $this->rows = $rows;
  }

  #[\ReturnTypeWillChange]
  public function getIterator() {
    return new ArrayIterator($this->fetchAll());
  }

  public function fetchAll() {
    return array_map(function ($row) {
      return (object) $row;
    }, $this->rows);
  }

  public function fetchAllAssoc($key) {
    $result = [];
    foreach ($this->fetchAll() as $row) {
      $result[$row->{$key}] = $row;
    }

    return $result;
  }

  /**
   * The first column keyed by the zeroth one (SPEC 121).
   *
   * Drupal's fetchAllKeyed() defaults to (0 => 1) — key from the first
   * projected column, value from the second — which is exactly how the
   * reservation calendar reads its condominium and area option lists. Keys come
   * out as the strings the driver answers, the same way they do in production,
   * so a test that compares them with === sees what a site would.
   */
  #[\ReturnTypeWillChange]
  public function fetchAllKeyed($key_index = 0, $value_index = 1) {
    $keyed = [];
    foreach ($this->rows as $row) {
      $values = array_values((array) $row);
      if (!array_key_exists($key_index, $values) || !array_key_exists($value_index, $values)) {
        continue;
      }
      $keyed[$values[$key_index]] = $values[$value_index];
    }

    return $keyed;
  }

  public function fetchCol($index = 0) {
    $column = [];
    foreach ($this->rows as $row) {
      $values = array_values($row);
      $column[] = isset($values[$index]) ? $values[$index] : NULL;
    }

    return $column;
  }

  public function fetchObject() {
    $rows = $this->fetchAll();

    return empty($rows) ? FALSE : $rows[0];
  }

  public function fetchAssoc() {
    return empty($this->rows) ? FALSE : $this->rows[0];
  }

  public function fetchField($index = 0) {
    $column = $this->fetchCol($index);

    return empty($column) ? FALSE : $column[0];
  }

  public function rowCount() {
    return count($this->rows);
  }

  #[\ReturnTypeWillChange]
  public function count() {
    return count($this->rows);
  }

}

/**
 * A db_or() / db_and() condition group (SPEC 77).
 *
 * Drupal's DatabaseCondition, reduced to what myapi builds with it: a
 * conjunction and a list of conditions, each of which may itself be a group.
 *
 * NESTING WAS A THROW UNTIL SPEC 98, on the grounds that no query in this
 * module nested one and that flattening a group into the wrong boolean in
 * silence is worse than failing. The provider scope is the first query that
 * genuinely nests — an OR of "n.nid IN (A ∪ C)" and an AND of the four market
 * conditions — so the tripwire fired exactly when it was meant to, and the
 * evaluator learnt to recurse instead. Anything that is neither a string nor
 * a group still throws.
 */
class MyapiTestConditionGroup {

  private $conjunction;
  private $conditions = [];

  public function __construct($conjunction) {
    $this->conjunction = $conjunction;
  }

  public function condition($field, $value = NULL, $operator = NULL) {
    if ($field instanceof MyapiTestConditionGroup) {
      $this->conditions[] = ['field' => NULL, 'group' => $field, 'operator' => 'GROUP'];

      return $this;
    }

    if (!is_string($field)) {
      throw new RuntimeException('MyapiTestConditionGroup: a condition is either a column or a group.');
    }
    $this->conditions[] = [
      'field'    => $field,
      'value'    => $value,
      'operator' => $operator !== NULL ? strtoupper($operator) : (is_array($value) ? 'IN' : '='),
    ];

    return $this;
  }

  public function isNull($field) {
    $this->conditions[] = ['field' => $field, 'value' => NULL, 'operator' => 'IS NULL'];

    return $this;
  }

  public function isNotNull($field) {
    $this->conditions[] = ['field' => $field, 'value' => NULL, 'operator' => 'IS NOT NULL'];

    return $this;
  }

  /**
   * A correlated EXISTS sub-select INSIDE a condition group (SPEC 121).
   *
   * Drupal's DatabaseCondition carries the same exists() as the query itself,
   * and the bulletin visibility rule is where that matters: its 'Personalizado'
   * branch is an OR of two db_and()s, and each of those ANDs a role comparison
   * with an EXISTS over a reference table. Written on the query instead, the
   * sub-select would apply to every branch and reveal a neighbour's bulletin.
   *
   * Recorded exactly like the query-level one, so matchesGroup() can evaluate
   * it with existsFor() against the outer row.
   */
  public function exists($select) {
    if (!$select instanceof MyapiTestSelectQuery) {
      throw new RuntimeException('MyapiTestConditionGroup: exists() takes a fixture sub-select.');
    }
    $this->conditions[] = ['field' => NULL, 'value' => $select, 'operator' => 'EXISTS'];

    return $this;
  }

  public function conjunction() {
    return $this->conjunction;
  }

  public function conditions() {
    return $this->conditions;
  }

}

