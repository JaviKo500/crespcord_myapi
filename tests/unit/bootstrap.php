/**
 * A SELECT over fixtures (SPEC 74).
 *
 * Implements the subset of Drupal 7's SelectQuery that myapi's read paths
 * actually use: fields(), addField(), condition(), the join family, orderBy(),
 * range(), since SPEC 79 groupBy() and addExpression() as well, and since SPEC
 * 83 exists() with its correlated sub-select and the non-aggregate expressions
 * an ORDER BY reads, plus execute(). Anything else throws instead of returning
 * a wrong answer quietly
 * — a resource that starts using an unsupported clause must extend this class
 * knowingly, not discover that its test passed for the wrong reason. That is
 * how grouping got here: the category counter was written, the stub threw, and
 * the aggregation was implemented rather than mocked around.
 *
 * The rules, in full:
 *  - The base table names the fixture: myapi_test_db_seed(['node' => [...]])
 *    is what a SELECT ... FROM node reads.
 *  - Conditions are applied over the fixture's own columns, with the alias
 *    prefix stripped ('n.status' matches the 'status' key). A condition on a
 *    column the fixture row does not carry is skipped, which is what lets a
 *    test seed only the columns its case is about.
 *  - Joins are recorded, never resolved. A joined column is seeded flat on the
 *    row under the alias the query gives it ('area_m2', not
 *    'field_total_m2_value'), because that alias is what production reads off
 *    the result.
 *  - The projection is the field list: each requested field/alias is copied
 *    from the row when present and NULL otherwise, in the order it was added.
 *    fields($alias) with no column list selects the row whole, as in Drupal.
 */
class MyapiTestSelectQuery implements IteratorAggregate {

  private $table;
  private $alias;
  private $fields = [];
  private $select_all = FALSE;
  private $conditions = [];
  private $where = [];
  private $correlations = [];
  private $joins = [];
  private $order = [];
  private $range = NULL;
  private $count_mode = FALSE;
  private $group_by = [];
  private $expressions = [];
  private $tags = [];
  private $extenders = [];
  private $pager_limit = NULL;
  private $field_sources = [];

  public function __construct($table, $alias) {
    $this->table = $table;
    $this->alias = $alias;
  }

  public function fields($table_alias, array $fields = []) {
    if (empty($fields)) {
      $this->select_all = TRUE;
    }
    foreach ($fields as $field) {
      $this->fields[] = $field;
      $this->field_sources[$field] = $table_alias . '.' . $field;
    }

    return $this;
  }

  public function addField($table_alias, $field, $alias = NULL) {
    $alias = $alias !== NULL ? $alias : $field;
    $this->fields[] = $alias;
    $this->field_sources[$alias] = $table_alias . '.' . $field;

    return $this;
  }

  public function condition($field, $value = NULL, $operator = NULL) {
    // A condition GROUP — db_or() / db_and() (SPEC 77). The claims endpoint
    // builds its whole visibility rule as one: "public OR filed by the
    // reader". Recorded as a single condition whose 'group' carries the
    // sub-conditions, so a test can read the shape as well as the outcome.
    if ($field instanceof MyapiTestConditionGroup) {
      $this->conditions[] = ['field' => NULL, 'value' => NULL, 'operator' => 'GROUP', 'group' => $field];

      return $this;
    }
    if (!is_string($field)) {
      throw new RuntimeException('MyapiTestSelectQuery: only string conditions are supported.');
    }
    $this->conditions[] = [
      'field'    => $field,
      'value'    => $value,
      'operator' => $operator !== NULL ? strtoupper($operator) : (is_array($value) ? 'IN' : '='),
    ];

    return $this;
  }

  /**
   * A query tag, recorded and never applied (SPEC 77).
   *
   * ->addTag('node_access') is how the back-office claims listing delegates
   * its condominium scoping to hook_query_alter(); the alter itself is
   * Drupal's dispatch and cannot run here. Recording the tag is what lets a
   * test assert the delegation happened — losing that call is the difference
   * between "an administrador edificio sees their buildings" and "sees every
   * building of the site", and nothing else in the query would show it.
   */
  public function addTag($tag) {
    $this->tags[] = $tag;

    return $this;
  }

  public function hasTag($tag) {
    return in_array($tag, $this->tags, TRUE);
  }

  /**
   * PagerDefault, as far as this layer can go (SPEC 77).
   *
   * The real extender reads $_GET['page'], runs its own COUNT(*) and computes
   * an offset. Here it records the extender and answers the same object, so
   * ->limit() below can behave like the range it ultimately becomes. What is
   * NOT simulated is the page offset: every fixture pager answers the FIRST
   * page. A test about page 2 of the back-office listing belongs to
   * tests/integration, and no case here pretends otherwise.
   */
  public function extend($class) {
    $this->extenders[] = $class;

    return $this;
  }

  public function limit($limit = 10) {
    $this->pager_limit = $limit;

    return $this->range(0, $limit);
  }

  public function isNull($field) {
    $this->conditions[] = ['field' => $field, 'value' => NULL, 'operator' => 'IS NULL'];

