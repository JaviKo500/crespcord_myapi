<?php

/**
 * @file
 * PHPUnit bootstrap for myapi unit tests.
 *
 * Lets tests `require` production .inc/.resource.inc files directly, outside
 * Drupal, with no copies. The only Drupal-level call these files make at file
 * scope (not inside a function) is module_load_include(), used by
 * resources/auth.resource.inc to pull in its includes/*.inc dependencies; this
 * stub makes that call a no-op so the require succeeds. Tests still `require`
 * the specific includes/*.inc files they actually exercise.
 *
 * If a future change adds another file-scope call to a Drupal function in one
 * of the .inc files exercised by tests/unit, this stub needs to grow to cover
 * it too — see tests/README.md.
 *
 * The four text helpers below (SPEC 50) are a different kind of stub: they are
 * called from INSIDE the functions under test, not at file scope, and each one
 * is a faithful one-line equivalent of the Drupal function for the only use
 * the tested code makes of it. They exist so the cancellation-reason texts can
 * be asserted character by character. Nothing here touches the database: the
 * suite still covers pure logic only.
 *
 * t() and form_set_error() (SPEC 52) are of that same kind, and are what makes
 * myapi_time_format_validate_fields() testable without a site: the walker is
 * shared by the 'area' and 'reservation' node forms, so one bug in it silences
 * the validation of four fields at once.
 *
 * drupal_get_path() and $base_url (SPEC 54) are the environment counterpart:
 * myapi_mail_logo_url() builds the header logo URL out of both, and every HTML
 * email template calls it, so without them the whole email suite fatals.
 *
 * element_children() (SPEC 59) is the same kind again: the only Drupal function
 * myapi_claim_transaction_transaction_form_alter() calls from inside, to walk
 * the langcode/delta levels of the field_claim widget.
 *
 * truncate_utf8() and drupal_substr() (SPEC 60) are what let the autogenerated
 * title of a 'claim_transaction' be asserted character by character: the title
 * cuts the operator's comment at 60 characters without breaking a word, and
 * that cut is core's, not myapi's.
 */

if (!function_exists('module_load_include')) {
  function module_load_include($type, $module, $name = NULL) {
    // No-op: unit tests require the relevant includes/*.inc files themselves.
  }
}

/**
 * The two halves of the logo URL myapi_mail_logo_url() assembles.
 *
 * Drupal resolves the path from the system table and $base_url from the
 * request; outside a site both are just constants, and the value only has to
 * be stable and plausible: no assertion reads the <img> src, it is the fatal
 * on the missing function that the tests need gone.
 */
if (!function_exists('drupal_get_path')) {
  function drupal_get_path($type, $name) {
    return 'sites/all/modules/' . $name;
  }
}

$GLOBALS['base_url'] = 'https://crespcord.example.com';

if (!function_exists('drupal_strlen')) {
  function drupal_strlen($text) {
    return mb_strlen($text, 'UTF-8');
  }
}

if (!function_exists('check_plain')) {
  function check_plain($text) {
    return htmlspecialchars($text, ENT_QUOTES, 'UTF-8');
  }
}

if (!function_exists('decode_entities')) {
  function decode_entities($text) {
    return html_entity_decode($text, ENT_QUOTES, 'UTF-8');
  }
}

if (!function_exists('format_date')) {
  /**
   * Only the 'custom' type is stubbed: it is the only one myapi calls, and it
   * maps straight onto date(). The site timezone is irrelevant here because
   * every fixture builds its timestamp with mktime() in the same one.
   */
  function format_date($timestamp, $type = 'medium', $format = '', $timezone = NULL, $langcode = NULL) {
    return date($format, $timestamp);
  }
}

if (!function_exists('drupal_substr')) {
  function drupal_substr($text, $start, $length = NULL) {
    return $length === NULL
      ? mb_substr($text, $start, NULL, 'UTF-8')
      : mb_substr($text, $start, $length, 'UTF-8');
  }
}

if (!function_exists('truncate_utf8')) {
  /**
   * Core's algorithm (includes/unicode.inc), reproduced (SPEC 60): the ellipsis
   * discounts its own character from the budget, $min_wordsafe_length bounds the
   * word-safe search, and a string with no boundary in range is cut hard.
   *
   * One declared divergence: core finds the cut with its own
   * PREG_CLASS_UNICODE_WORD_BOUNDARY character class, this uses '\s'. Every
   * fixture in ClaimTransactionTitleTest cuts on a plain space, where the two
   * agree; a fixture cutting on a hyphen or a comma would not, and that is why
   * none does.
   */
  function truncate_utf8($string, $max_length, $wordsafe = FALSE, $add_ellipsis = FALSE, $min_wordsafe_length = 1) {
    $ellipsis = '';
    $max_length = max($max_length, 0);
    $min_wordsafe_length = max($min_wordsafe_length, 0);

    if (drupal_strlen($string) <= $max_length) {
      return $string;
    }

    if ($add_ellipsis) {
      $ellipsis = drupal_substr('…', 0, $max_length);
      $max_length = max($max_length - drupal_strlen($ellipsis), 0);
    }

    if ($max_length <= $min_wordsafe_length) {
      $wordsafe = FALSE;
    }

    $matches = array();
    if ($wordsafe && preg_match('/^(.{' . $min_wordsafe_length . ',' . $max_length . '})\s/u', $string, $matches)) {
      $string = $matches[1];
    }
    else {
      $string = drupal_substr($string, 0, $max_length);
    }

    return $string . $ellipsis;
  }
}

if (!function_exists('t')) {
  /**
   * The placeholder substitution only: no string catalogue is involved outside
   * Drupal, and every myapi caller passes '@name' style placeholders, which
   * Drupal itself resolves with strtr() after check_plain(). Sanitisation is
   * left out on purpose — the tested code asserts the message text, and
   * escaping it here would only make the assertions harder to read.
   */
  function t($string, array $args = [], array $options = []) {
    return $args ? strtr($string, $args) : $string;
  }
}

if (!function_exists('form_set_error')) {
  /**
   * Records the error instead of touching a form: Drupal keeps these in a
   * static and prints them on the next page load, which is not observable from
   * a unit test. The recorded map is keyed by the element path exactly as the
   * production code builds it, so a test can assert WHICH input would be
   * flagged and not just how many errors came out.
   *
   * Tests reset $GLOBALS['myapi_test_form_errors'] in setUp(); the null
   * coalescing keeps a stray call outside a test from fataling.
   */
  function form_set_error($name = NULL, $message = '') {
    $GLOBALS['myapi_test_form_errors'] = $GLOBALS['myapi_test_form_errors'] ?? [];
    $GLOBALS['myapi_test_form_errors'][$name] = $message;
    return $GLOBALS['myapi_test_form_errors'];
  }
}

if (!function_exists('element_children')) {
  /**
   * Every key that is not a '#property'. Drupal's own version also sorts by
   * '#weight' when asked; myapi never asks, and the widget's deltas are
   * already in order, so the sort is left out on purpose.
   *
   * The is_int() branch is the PHP 7.4 guard: field widget deltas are integer
   * keys, and $key[0] on an int raises "Trying to access array offset on value
   * of type int". An integer key is never a '#property', so short-circuiting
   * on it is faithful to the original rather than a deviation from it.
   */
  function element_children(&$elements, $sort = FALSE) {
    $children = array();
    foreach ($elements as $key => $value) {
      if (is_int($key) || $key === '' || $key[0] !== '#') {
        $children[] = $key;
      }
    }

    return $children;
  }
}

if (!function_exists('form_load_include')) {
  /**
   * The bookkeeping half of Drupal's own, which is the half that matters here:
   * the file is recorded in $form_state['build_info']['files'] so Drupal can
   * reload it when it retrieves a CACHED form — without it, a #submit handler
   * living in an .inc is an undefined function on POST. The loading half is
   * the module_load_include() stubbed above, i.e. a no-op out of Drupal.
   */
  function form_load_include(&$form_state, $type, $module, $name = NULL) {
    if (!isset($name)) {
      $name = $module;
    }
    if (!isset($form_state['build_info']['files']["$module:$name.$type"])) {
      $form_state['build_info']['files']["$module:$name.$type"] = array(
        'type' => $type,
        'module' => $module,
        'name' => $name,
      );

      return module_load_include($type, $module, $name);
    }

    return FALSE;
  }
}
